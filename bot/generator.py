def _bibliography(sources: list[Source], article: str) -> str:
    """Use only verified source URLs actually cited by the model."""
    cited = {int(m) for m in re.findall(r"(?<!\w)\[(\d+)\](?!\()", article)}
    allowed = {source.number for source in sources}
    if not cited:
        raise ValueError("Модель не поставила ссылки [1], [2] в тексте. Попробуй генерацию ещё раз.")
    if not cited.issubset(allowed):
        raise ValueError("Модель сослалась на источник, которого нет в запросе.")
    lines = ["## Список литературы", ""]
    for source in sources:
        if source.number in cited:
            title = re.sub(r"([\\\[\]])", r"\\\1", source.title).replace("\n", " ")
            safe_url = source.url.replace(">", "%3E")
            lines.append(f"{source.number}. [{title}](<{safe_url}>)")
    return "\n".join(lines)


async def generate_article(materials: str) -> str:
    """Keep the existing function signature used by bot/main.py."""
    if not materials.strip():
        raise ValueError("Укажи тему, ссылки на первоисточники и свои комментарии.")

    sources = await load_sources(materials)
    source_context = "\n\n".join(
        f"ИСТОЧНИК [{item.number}]\n"
        f"Название: {item.title}\n"
        f"URL: {item.url}\n"
        f"ИЗВЛЕЧЁННЫЙ ТЕКСТ (может быть сокращён):\n{item.text}"
        for item in sources
    )
    user_message = (
        "ЗАДАНИЕ И КОММЕНТАРИИ АВТОРА:\n"
        f"{materials}\n\n"
        "ПРОВЕРЕННЫЕ ДОСТУПНЫЕ ИСТОЧНИКИ:\n"
        f"{source_context}\n\n"
        "Напиши статью, используя указанные источники и авторские замечания. "
        "Для утверждений, основанных на них, ставь [номер источника]."
    )

    async with httpx.AsyncClient(timeout=180) as client:
        response = await client.post(
            OPENROUTER_URL,
            headers={"Authorization": f"Bearer {os.environ['OPENROUTER_API_KEY']}"},
            json={
                "model": os.environ["OPENROUTER_MODEL"],
                "messages": [
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": user_message},
                ],
                "max_tokens": 4000,
                "temperature": 0.3,
            },
        )
        response.raise_for_status()
        content = response.json()["choices"][0]["message"]["content"]

    if not isinstance(content, str) or not content.strip():
        raise ValueError("OpenRouter вернул пустую статью.")
    article = content.strip()
    if not re.match(r"^#\s+\S", article):
        raise ValueError("Модель вернула Markdown без заголовка #. Попробуй повторить запрос.")
    if re.search(r"^##\s+Список литературы\s*$", article, flags=re.MULTILINE | re.IGNORECASE):
        article = re.split(r"^##\s+Список литературы\s*$", article, flags=re.MULTILINE | re.IGNORECASE)[0].rstrip()
    return article + "\n\n" + _bibliography(sources, article) + "\n"
